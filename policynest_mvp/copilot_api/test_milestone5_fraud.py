    # 7. Composite Risk Scoring & Automatic High-Risk Hold
    def test_composite_risk_scoring_and_automated_high_risk_hold(self):
        app = application.get_or_create_application(self.applicant_1)

        fraud_ops.add_to_blacklist(
            self.fraud_inv,
            identifier_type="PAN",
            identifier_value="BLACK9999F",
            reason="High risk syndicate PAN",
        )

        with auth._db() as db:
            db.execute(
                "UPDATE applications SET details=? WHERE id=?",
                (json.dumps({"name": "Test User", "pan": "BLACK9999F"}), app["id"]),
            )
            db.execute("INSERT OR IGNORE INTO cases (id, applicant_id, status) VALUES ('C1', ?, 'IN_REVIEW')", (self.applicant_1["id"],))

        eval_res = fraud_engine.evaluate_application_risk(app["id"])
