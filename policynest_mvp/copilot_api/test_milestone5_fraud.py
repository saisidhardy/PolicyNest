    # 5. IP Address Onboarding Velocity & Syndicate Detection
    def test_network_ip_velocity_anomaly_detection(self):
        test_ip = "198.51.100.42"

        fraud_engine.record_network_event(self.applicant_1["id"], 1, test_ip, "Mozilla/5.0", "LOGIN")
        fraud_engine.record_network_event(self.applicant_2["id"], 2, test_ip, "Mozilla/5.0", "SUBMIT")

        res_2 = fraud_engine.check_ip_velocity(self.applicant_1["id"], test_ip, window_hours=24)
        self.assertFalse(res_2["high_velocity"])
        self.assertEqual(res_2["count"], 2)

        fraud_engine.record_network_event(self.applicant_3["id"], 3, test_ip, "Mozilla/5.0", "UPLOAD")
        res_3 = fraud_engine.check_ip_velocity(self.applicant_3["id"], test_ip, window_hours=24)
        self.assertTrue(res_3["high_velocity"])
        self.assertGreaterEqual(res_3["count"], 3)

