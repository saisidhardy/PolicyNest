    # 10. Investigator Decision: CONFIRMED_FRAUD (Anti-Accusation Invariant)
    def test_investigator_decision_confirmed_fraud_anti_accusation(self):
        app = application.get_or_create_application(self.applicant_1)
        eval_res = fraud_engine.evaluate_application_risk(app["id"])

        q_res = fraud_ops.list_fraud_cases(self.fraud_inv, status_filter="ALL")
        fc_id = [c["id"] for c in q_res["cases"] if c["application_id"] == app["id"]][0]

        dec_res = fraud_ops.decide_fraud_case(
            self.fraud_inv,
            case_id=fc_id,
            decision="CONFIRMED_FRAUD",
            notes="Confirmed synthetic identity with forged documents after manual verification.",
            blacklist_identifiers=[{"type": "PAN", "value": "FORGEDPAN1"}],
        )
        self.assertTrue(dec_res["ok"])
        self.assertEqual(dec_res["decision"], "CONFIRMED_FRAUD")

        with auth._db() as db:
            app_row = db.execute("SELECT status, risk_hold FROM applications WHERE id=?", (app["id"],)).fetchone()
            self.assertEqual(app_row[0], "REJECTED")
            self.assertEqual(app_row[1], 1)

            audit_row = db.execute("SELECT action FROM audit_events WHERE action='FRAUD_CONFIRMED'").fetchone()
            self.assertIsNotNone(audit_row)

            bl_row = db.execute("SELECT identifier_value FROM fraud_blacklist WHERE identifier_value='FORGEDPAN1'").fetchone()
            self.assertIsNotNone(bl_row)

            # Strict Anti-Accusation Invariant: Public timeline and notification messages MUST NOT contain banned words
            tl_rows = db.execute("SELECT key FROM timeline WHERE user_id=?", (self.applicant_1["id"],)).fetchall()
            for r in tl_rows:
                self.assertIsNone(re.search(r"fraud|fake|forged|tamper|suspicious|blacklisted", r[0], re.I))

            notif_rows = db.execute("SELECT key FROM notifications WHERE user_id=?", (self.applicant_1["id"],)).fetchall()
            for r in notif_rows:
                self.assertIsNone(re.search(r"fraud|fake|forged|tamper|suspicious|blacklisted", r[0], re.I))

    # 11. Investigator Decision: CLEARED_FALSE_POSITIVE (Lifting Risk Hold)
    def test_investigator_decision_cleared_false_positive_restores_review(self):
        app = application.get_or_create_application(self.applicant_2)
        with auth._db() as db:
            db.execute("UPDATE applications SET risk_hold=1 WHERE id=?", (app["id"],))
            db.execute("INSERT OR REPLACE INTO cases (id, applicant_id, status) VALUES ('C2', ?, 'FRAUD_HOLD')", (self.applicant_2["id"],))

        eval_res = fraud_engine.evaluate_application_risk(app["id"])
        q_res = fraud_ops.list_fraud_cases(self.fraud_inv, status_filter="ALL")
        fc_id = [c["id"] for c in q_res["cases"] if c["application_id"] == app["id"]][0]

        dec_res = fraud_ops.decide_fraud_case(
            self.fraud_inv,
            case_id=fc_id,
            decision="CLEARED_FALSE_POSITIVE",
            notes="Applicant provided valid offline utility bill and bank certificate explaining name variation.",
        )
        self.assertTrue(dec_res["ok"])
        self.assertEqual(dec_res["decision"], "CLEARED_FALSE_POSITIVE")

        with auth._db() as db:
            app_row = db.execute("SELECT status, risk_hold FROM applications WHERE id=?", (app["id"],)).fetchone()
            self.assertEqual(app_row[0], "UNDER_REVIEW")
            self.assertEqual(app_row[1], 0)

            case_row = db.execute("SELECT status FROM cases WHERE applicant_id=?", (self.applicant_2["id"],)).fetchone()
            self.assertEqual(case_row[0], "IN_REVIEW")

