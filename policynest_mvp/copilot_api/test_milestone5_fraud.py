    # 1. Forensic Image Manipulation Detection
    def test_image_byte_forensic_analysis_editing_signatures(self):
        clean_bytes = b"\x89PNG\r\n\x1a\n" + b"\x00" * 200
        res_clean = fraud_engine.inspect_image_bytes(clean_bytes)
        self.assertFalse(res_clean["editing_tool_detected"])
        self.assertIsNone(res_clean["tool_name"])

        # Photoshop signature
        ps_bytes = b"\xff\xd8\xff\xe0" + b"\x00" * 20 + b"Adobe Photoshop CC 2024" + b"\x00" * 100
        res_ps = fraud_engine.inspect_image_bytes(ps_bytes)
        self.assertTrue(res_ps["editing_tool_detected"])
        self.assertEqual(res_ps["tool_name"], "Adobe Photoshop")

        # Canva signature
        canva_bytes = b"\x89PNG\r\n\x1a\n" + b"Generated by Canva web designer" + b"\x00" * 100
        res_canva = fraud_engine.inspect_image_bytes(canva_bytes)
        self.assertTrue(res_canva["editing_tool_detected"])
        self.assertEqual(res_canva["tool_name"], "Canva")

    # 2. Duplicate Asset Detection (SHA-256 Reused Across Applicants)
    def test_cross_applicant_duplicate_document_hash_detection(self):
        app1 = application.get_or_create_application(self.applicant_1)
        app2 = application.get_or_create_application(self.applicant_2)

        test_doc_bytes = b"\x89PNG\r\n\x1a\n" + b"UniqueCertificateBytes" + b"\x00" * 300
        doc_hash = hashlib.sha256(test_doc_bytes).hexdigest()

        # Applicant 1 uploads document
        with auth._db() as db:
            db.execute(
                """INSERT INTO document_records (
                    id, application_id, user_id, slot, doc_type, mime_type, file_size,
                    storage_path, sha256_hash, status, quality_score, created_at, updated_at
                ) VALUES (?, ?, ?, 'CLASS10', 'class10', 'image/png', 320, 'path1', ?, 'UPLOADED', 90, 1000, 1000)""",
                (f"doc_{self.applicant_1['id']}", app1["id"], self.applicant_1["id"], doc_hash),
            )

            # Applicant 2 uploads same document
            db.execute(
                """INSERT INTO document_records (
                    id, application_id, user_id, slot, doc_type, mime_type, file_size,
                    storage_path, sha256_hash, status, quality_score, created_at, updated_at
                ) VALUES (?, ?, ?, 'CLASS10', 'class10', 'image/png', 320, 'path2', ?, 'UPLOADED', 90, 1000, 1000)""",
                (f"doc_{self.applicant_2['id']}", app2["id"], self.applicant_2["id"], doc_hash),
            )

        conflicts = fraud_engine.check_duplicate_document_hashes(app2["id"], self.applicant_2["id"])
        self.assertEqual(len(conflicts), 1)
        self.assertEqual(conflicts[0]["conflict_user_id"], self.applicant_1["id"])
        self.assertEqual(conflicts[0]["sha256"], doc_hash)

    # 3. Duplicate PAN Detection Across Applicants
    def test_duplicate_pan_detection_across_applicants(self):
        app1 = application.get_or_create_application(self.applicant_1)
        app2 = application.get_or_create_application(self.applicant_2)

        with auth._db() as db:
            db.execute(
                "UPDATE applications SET details=? WHERE id=?",
                (json.dumps({"name": "Applicant One", "pan": "ABCDE1234F"}), app1["id"]),
            )
            db.execute(
                """INSERT INTO verification_results (
                    id, application_id, provider, check_type, status, match_score, response_digest, created_at
                ) VALUES ('vr1', ?, 'protean_pan', 'PAN', 'PASS', 1.0, 'digest1', 1000)""",
                (app1["id"],),
            )
            db.execute(
                "UPDATE applications SET details=? WHERE id=?",
                (json.dumps({"name": "Applicant Two", "pan": "ABCDE1234F"}), app2["id"]),
            )

        dup = fraud_engine.check_duplicate_pan(self.applicant_2["id"], app2["id"], "ABCDE1234F")
        self.assertIsNotNone(dup)
        self.assertTrue(dup["duplicate"])
        self.assertEqual(dup["conflict_user_id"], self.applicant_1["id"])

